FORWARD = r"""
ALTER TABLE quality_lotinspection ALTER COLUMN id SET GENERATED ALWAYS;

CREATE FUNCTION quality_lot_origin_kind(lot bigint)
RETURNS text LANGUAGE sql STABLE AS $$
    SELECT CASE
        WHEN EXISTS (
            SELECT 1 FROM inventory_productionposting p
            JOIN inventory_stockledgerentry e ON e.id = p.ledger_entry_id
            WHERE e.lot_id = $1 AND p.kind = 'OUTPUT') THEN 'FINAL'
        WHEN EXISTS (
            SELECT 1 FROM inventory_stockreceipt r
            JOIN inventory_stockledgerentry e ON e.id = r.ledger_entry_id
            WHERE e.lot_id = $1) THEN 'INCOMING'
    END;
$$;

CREATE FUNCTION quality_validate_inspection_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    lot_organization_id bigint;
    warehouse_organization_id bigint;
BEGIN
    NEW.created_at := statement_timestamp();
    -- Same Lot lock as disposition events: one history per Lot at a time.
    PERFORM id FROM inventory_lot WHERE id = NEW.lot_id FOR UPDATE;
    SELECT item.organization_id INTO lot_organization_id
    FROM inventory_lot AS lot JOIN catalog_item AS item ON item.id = lot.item_id
    WHERE lot.id = NEW.lot_id;
    SELECT plant.organization_id INTO warehouse_organization_id
    FROM facilities_warehouse AS warehouse
    JOIN facilities_plant AS plant ON plant.id = warehouse.plant_id
    WHERE warehouse.id = NEW.warehouse_id;
    IF lot_organization_id IS DISTINCT FROM warehouse_organization_id THEN
        RAISE EXCEPTION 'lot and warehouse belong to different organizations'
            USING ERRCODE = '23514';
    END IF;
    IF quality_lot_origin_kind(NEW.lot_id) IS DISTINCT FROM NEW.kind THEN
        RAISE EXCEPTION 'inspection kind % does not match the Lot origin %',
            NEW.kind, quality_lot_origin_kind(NEW.lot_id)
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER quality_inspection_validate_insert
BEFORE INSERT ON quality_lotinspection FOR EACH ROW
EXECUTE FUNCTION quality_validate_inspection_insert();

CREATE FUNCTION quality_reject_inspection_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'lot inspections are append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER quality_inspection_reject_mutation
BEFORE UPDATE OR DELETE ON quality_lotinspection FOR EACH ROW
EXECUTE FUNCTION quality_reject_inspection_mutation();

CREATE FUNCTION quality_require_inspection_event()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM quality_lotdispositionevent e
        WHERE e.inspection_id = NEW.id
          AND e.lot_id = NEW.lot_id AND e.warehouse_id = NEW.warehouse_id) THEN
        RAISE EXCEPTION 'an inspection must be linked by its disposition event'
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER quality_inspection_requires_event
AFTER INSERT ON quality_lotinspection DEFERRABLE INITIALLY DEFERRED FOR EACH ROW
EXECUTE FUNCTION quality_require_inspection_event();
"""

